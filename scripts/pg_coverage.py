"""Measure the PostgreSQL grammar checklist and write its report.

    .\\.venv\\Scripts\\python.exe scripts\\pg_coverage.py           # regenerate both files
    .\\.venv\\Scripts\\python.exe scripts\\pg_coverage.py --check   # exit 1 if either is stale

Runs every row of `stress/pg/grammar/checklist.yaml` through `analyse_source` and writes:

* `stress/pg/grammar/measured.json` - each row's measured outcome and the column pairs it
  produced: the snapshot `tests/test_pg_checklist.py` compares against, so any change in
  what the analyser does with a construct is a reviewed diff, never a silent one;
* `docs/pg-coverage.md` - the coverage statement: per area, how many of PostgreSQL's
  constructs meet their target, and every one that does not.

Rows whose snippet PostgreSQL rejects, or whose parse does not contain the construct they
claim, are reported and fail `--check`: a row that does not test what it says is worse
than no row.
"""

from __future__ import annotations

import json
import logging
import sys
from collections import Counter, defaultdict

from lineage.coverage.grammar import (
    DDL_DETAIL_FIELDS,
    EXCLUDED,
    REPORT,
    SNAPSHOT,
    UNREACHABLE,
    constructs,
    inventory,
    load_rows,
    measure_all,
    met,
)

AREAS = ("statement", "clause", "expression / clause", "variant", "PL/pgSQL")


def run() -> tuple[dict, str, list[str]]:
    items = inventory()
    rows = load_rows()
    outcomes = measure_all([row.sql for row in rows])
    problems: list[str] = []
    measured: dict[str, dict] = {}
    for row, (status, pairs) in zip(rows, outcomes, strict=True):
        claimed = [item for item in row.items if not item.startswith("extra:")]
        problems.extend(
            f"{row.id}: {item} is not an inventory item" for item in claimed if item not in items
        )
        try:
            found = constructs(row.sql)
        except Exception as error:
            problems.append(f"{row.id}: PostgreSQL rejects the snippet - {error}")
            found = set()
        else:
            problems.extend(
                f"{row.id}: the snippet's parse does not contain {item}"
                for item in claimed
                if item not in found
            )
        key = row.id if row.id not in measured else f"{row.id}#{len(measured)}"
        measured[key] = {
            "covers": row.covers,
            "target": row.target,
            "status": status,
            "met": met(row.target, status, pairs, row.reach),
            "pairs": pairs,
        }
    covered = {item for row in rows for item in row.items}
    missing = sorted(set(items) - covered)
    problems.extend(f"{item}: no checklist row" for item in missing)
    return measured, render(items, rows, measured, missing), problems


def render(items: dict, rows: list, measured: dict, missing: list[str]) -> str:
    by_id: dict[str, list[dict]] = defaultdict(list)
    for key, value in measured.items():
        for item in (key.split("#")[0], *value["covers"]):
            by_id[item].append(value)
    area_total: Counter = Counter()
    area_met: Counter = Counter()
    for item, area in items.items():
        area_total[area] += 1
        if by_id.get(item) and all(v["met"] for v in by_id[item]):
            area_met[area] += 1
    extras = [k for k in measured if k.startswith("extra:")]
    extras_met = sum(measured[k]["met"] for k in extras)
    total, total_met = sum(area_total.values()), sum(area_met.values())
    statuses = Counter(v["status"].split(":")[0] for v in measured.values())

    lines = [
        "# PostgreSQL grammar coverage",
        "",
        "**Generated by `scripts/pg_coverage.py` - do not edit.** The construct list is read",
        "out of PostgreSQL's own parser (libpg_query, via pglast), not written by hand, so a",
        "construct nobody thought of still has a row. Each row's outcome is measured by running",
        "its snippet through `analyse_source`. Rows: `stress/pg/grammar/checklist.yaml`.",
        "",
        f"**{total_met} / {total} constructs meet their target ({100 * total_met / total:.1f}%).**"
        f" Extra combinations: {extras_met} / {len(extras)}.",
        "",
        "| area | constructs | meet target | % |",
        "|---|---|---|---|",
    ]
    for area in AREAS:
        t, m = area_total[area], area_met[area]
        lines.append(f"| {area} | {t} | {m} | {100 * m / max(1, t):.1f}% |")
    lines += [
        "",
        "Measured outcomes over all rows: "
        + ", ".join(f"{k} {v}" for k, v in sorted(statuses.items())),
        "",
        "## Targets and outcomes",
        "",
        "| target | meaning | met by |",
        "|---|---|---|",
        "| lineage | column lineage; every listed pair among it | LINEAGE |",
        "| no_lineage | nothing to trace (DDL, settings, grants) | COUNTED |",
        "| effect | changes what a table holds or is (TRUNCATE, DROP) |"
        " an Operation fact - not built yet |",
        "| refused:C / declared:K | honestly unknowable, named | REFUSED:C / DECLARED:K |",
        "",
        "SILENT means the analyser did not even count the statement - the case the statement",
        "ledger (plan step 3) ends. PARTIAL means lineage came out and a part was refused.",
        "",
        "## Not meeting target",
        "",
        "| construct | target | measured | note |",
        "|---|---|---|---|",
    ]
    notes = {row.id: row.note for row in rows}
    for key, value in sorted(measured.items(), key=lambda kv: (kv[1]["target"], kv[0])):
        if not value["met"]:
            note = notes.get(key.split("#")[0], "")
            lines.append(f"| `{key}` | {value['target']} | {value['status']} | {note} |")
    if missing:
        lines += ["", "## Constructs with no row", ""]
        lines += [f"- `{item}`" for item in missing]
    lines += [
        "",
        "## Left out of the inventory, by name",
        "",
        "| construct | why |",
        "|---|---|",
    ]
    for key, why in sorted({**EXCLUDED, **UNREACHABLE}.items()):
        lines.append(f"| `{key}` | {why} |")
    lines += ["", "Enum fields whose values are DDL detail (each node still has its own row):", ""]
    lines += [f"- `{name}` - {why}" for name, why in sorted(DDL_DETAIL_FIELDS.items())]
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    logging.getLogger("sqlglot").setLevel(logging.CRITICAL)
    measured, report, problems = run()
    snapshot = json.dumps(measured, indent=1, sort_keys=True) + "\n"
    for problem in problems:
        print(f"PROBLEM  {problem}")
    if "--check" in sys.argv:
        stale = [
            path.name
            for path, text in ((SNAPSHOT, snapshot), (REPORT, report))
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for name in stale:
            print(f"STALE    {name} - run scripts/pg_coverage.py")
        return 1 if stale or problems else 0
    SNAPSHOT.write_text(snapshot, encoding="utf-8", newline="\n")
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    print(report.split("\n\n")[2])
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
